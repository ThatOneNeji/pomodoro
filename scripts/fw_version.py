"""
PlatformIO pre-build script: writes src/version_generated.h with the firmware version from
`git describe --tags --always --dirty` (e.g. "v0.1.0-3-g4dfefc1-dirty", or just the commit hash
until the repo has tags) and the build time.

Only src/version.cpp includes that header, so a new commit recompiles one small file rather than
everything (which a -DFW_VERSION=... build flag would do). The header is gitignored. Outside a git
checkout (e.g. a downloaded zip), the version is "unknown" rather than failing the build.
"""

import os
import subprocess
from datetime import datetime, timezone

Import("env")  # noqa: F821 (provided by PlatformIO's SCons environment)


def git_describe(project_dir):
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


version = git_describe(env.subst("$PROJECT_DIR"))  # noqa: F821
build_time = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
header = (
    "// GENERATED by scripts/fw_version.py at build time. Do not edit or commit.\n"
    "#pragma once\n"
    f'#define FW_VERSION "{version}"\n'
    f'#define FW_BUILD_TIME "{build_time}"\n'
)

path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "version_generated.h")  # noqa: F821
try:
    with open(path) as f:
        current = f.read()
except FileNotFoundError:
    current = None

# Build time is in minutes, so back-to-back builds don't rewrite it; when it does change, only
# version.cpp recompiles.
if current != header:
    with open(path, "w") as f:
        f.write(header)
print(f"Firmware version: {version} (built {build_time})")
