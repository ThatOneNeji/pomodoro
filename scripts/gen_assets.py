"""
Generates the firmware's bitmap assets from assets/manifest.json:

    src/icons.h, src/icons/icons.cpp   icons ('svg' from assets/svg/, or 'png' from assets/)
    src/images.h, src/images/*.h       full-screen 800x480 background images

Only the sizes listed per icon are generated, since each one costs flash. Assets marked
"meme": true are wrapped in `#if INCLUDE_MEME_ASSETS` (see src/config.h), so a default build
doesn't contain them at all.

Usage (from the repo root):
    uv run python scripts/gen_assets.py           # icons + images
    uv run python scripts/gen_assets.py --fonts   # also regenerate src/fonts/ (needs fontconvert
                                                  # and assets/fonts/*.ttf, which are gitignored)
"""

import argparse
import io
import json
import os
import shutil
import subprocess

import resvg_py
from PIL import Image

ASSETS_DIR = "assets"
MANIFEST_FILE = os.path.join(ASSETS_DIR, "manifest.json")
SVG_DIR = os.path.join(ASSETS_DIR, "svg")
OUTPUT_DIR = "src"
ICONS_DIR = os.path.join(OUTPUT_DIR, "icons")
IMAGES_DIR = os.path.join(OUTPUT_DIR, "images")
ICONS_HEADER_FILE = os.path.join(OUTPUT_DIR, "icons.h")
ICONS_SOURCE_FILE = os.path.join(ICONS_DIR, "icons.cpp")
IMAGES_AGGREGATE_HEADER_FILE = os.path.join(OUTPUT_DIR, "images.h")

ICON_SIZES = [192, 128, 64, 48]  # the sizes the Icon class (src/icon.h) has slots for
IMAGE_SIZE = (800, 480)
MEME_GUARD = "INCLUDE_MEME_ASSETS"
GENERATED_NOTE = "GENERATED by scripts/gen_assets.py from assets/manifest.json. Do not edit by hand."


def image_to_c_array(image):
    """1-bit image -> row-major bytes, MSB first, with a set bit for each black pixel."""
    width, height = image.size
    byte_data = []
    for y in range(height):
        byte_val, bit_count = 0, 0
        for x in range(width):
            if image.getpixel((x, y)) == 0:  # BLACK pixel
                byte_val |= 1 << (7 - bit_count)
            bit_count += 1
            if bit_count == 8:
                byte_data.append(byte_val)
                byte_val, bit_count = 0, 0
        if bit_count > 0:
            byte_data.append(byte_val)
    return byte_data


def flatten_to_grayscale(img):
    """Composite any transparency onto white and return a grayscale ("L") image."""
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        background = Image.new("RGB", img.size, (255, 255, 255))
        background.paste(img, mask=img.split()[3])
        img = background
    return img.convert("L")


def render_svg_icon(svg_name, size):
    """Render a Bootstrap icon straight at `size` px and threshold it: crisp edges, no dither speckle."""
    svg_path = os.path.join(SVG_DIR, f"{svg_name}.svg")
    if not os.path.exists(svg_path):
        raise SystemExit(f"❌ SVG not found: {svg_path}")
    png = resvg_py.svg_to_bytes(svg_path=svg_path, width=size, height=size)
    gray = flatten_to_grayscale(Image.open(io.BytesIO(bytes(png))))
    return gray.point(lambda p: 255 if p >= 128 else 0).convert("1", dither=Image.Dither.NONE)


def render_png_icon(png_path, size):
    """Downscale drawn art and dither it, which suits shading better than a hard threshold."""
    gray = flatten_to_grayscale(Image.open(os.path.join(ASSETS_DIR, png_path)))
    return gray.resize((size, size), Image.LANCZOS).convert("1", dither=Image.Dither.FLOYDSTEINBERG)


def write_c_array(f, name, data, storage=""):
    f.write(f"{storage}const unsigned char {name}[] = {{\n    ")
    for i, byte in enumerate(data):
        f.write(f"0x{byte:02X}, ")
        if (i + 1) % 12 == 0:
            f.write("\n    ")
    f.write("\n};\n")


def source_note(entry):
    if "svg" in entry:
        return f'Bootstrap Icons "{entry["svg"]}" (MIT).'
    return f"From assets/{entry['png']}."


def grouped(entries):
    """Yield (meme, [(name, entry), ...]) with non-meme assets first, preserving manifest order."""
    for meme in (False, True):
        group = [(n, e) for n, e in entries.items() if bool(e.get("meme")) == meme]
        if group:
            yield meme, group


def generate_icons(icons):
    os.makedirs(ICONS_DIR, exist_ok=True)
    total = {False: 0, True: 0}

    with open(ICONS_SOURCE_FILE, "w") as cpp:
        cpp.write(f"/// @file icons.cpp\n/// {GENERATED_NOTE}\n")
        cpp.write('#include "icons.h"\n')
        for meme, group in grouped(icons):
            if meme:
                cpp.write(f"\n#if {MEME_GUARD}\n")
            for name, entry in group:
                sizes = entry["sizes"]
                unknown = [s for s in sizes if s not in ICON_SIZES]
                if not sizes or unknown:
                    raise SystemExit(f"❌ icon '{name}': sizes must be a non-empty subset of {ICON_SIZES}")
                slots = []
                for size in ICON_SIZES:
                    if size not in sizes:
                        slots.append("nullptr")
                        continue
                    bitmap = render_svg_icon(entry["svg"], size) if "svg" in entry else render_png_icon(entry["png"], size)
                    data = image_to_c_array(bitmap)
                    total[meme] += len(data)
                    cpp.write("\n")
                    write_c_array(cpp, f"icon_{name}_{size}", data, storage="static ")
                    slots.append(f"icon_{name}_{size}")
                cpp.write(f"\nIcon icon_{name}({', '.join(slots)});\n")
                print(f"  icon  {name:<12} {str(sizes):<12} {sum(s * s // 8 for s in sizes):>7,} B{'  (meme)' if meme else ''}")
            if meme:
                cpp.write(f"\n#endif  // {MEME_GUARD}\n")

    with open(ICONS_HEADER_FILE, "w") as h:
        h.write("/**\n * @file icons.h\n * @brief The Icon instances compiled into the firmware, defined in src/icons/icons.cpp.\n")
        h.write(f" *\n * {GENERATED_NOTE}\n * Only the sizes listed in the manifest exist; see Icon::scaled().\n */\n")
        h.write("#ifndef ICONS_H\n#define ICONS_H\n\n#include \"config.h\"\n#include \"icon.h\"\n")
        for meme, group in grouped(icons):
            h.write(f"\n#if {MEME_GUARD}\n" if meme else "\n")
            for name, entry in group:
                h.write(f"extern Icon icon_{name};  ///< {entry['doc']} {source_note(entry)} Sizes: {entry['sizes']}.\n")
            if meme:
                h.write(f"#endif  // {MEME_GUARD}\n")
        h.write("\n#endif  // ICONS_H\n")
    return total


def generate_images(images):
    os.makedirs(IMAGES_DIR, exist_ok=True)
    total = {False: 0, True: 0}

    for name, entry in images.items():
        img = flatten_to_grayscale(Image.open(os.path.join(ASSETS_DIR, entry["png"])))
        if img.size != IMAGE_SIZE:
            raise SystemExit(f"❌ image '{name}' is {img.size[0]}x{img.size[1]}, expected {IMAGE_SIZE[0]}x{IMAGE_SIZE[1]}")
        data = image_to_c_array(img.convert("1", dither=Image.Dither.FLOYDSTEINBERG))
        total[bool(entry.get("meme"))] += len(data)
        guard = f"IMAGE_{name.upper()}_H"
        with open(os.path.join(IMAGES_DIR, f"image_{name}.h"), "w") as f:
            f.write(f"/// @file image_{name}.h\n/// {GENERATED_NOTE}\n")
            f.write(f"#ifndef {guard}\n#define {guard}\n\n")
            f.write(f"/// {entry['doc']} {source_note(entry)}\n")
            write_c_array(f, f"image_{name}", data)
            f.write(f"\n#endif  // {guard}\n")
        print(f"  image {name:<26} {len(data):>7,} B{'  (meme)' if entry.get('meme') else ''}")

    # Remove headers for images that have left the manifest, so they can't linger unused.
    keep = {f"image_{name}.h" for name in images}
    for stale in sorted(os.listdir(IMAGES_DIR)):
        if stale.startswith("image_") and stale.endswith(".h") and stale not in keep:
            os.remove(os.path.join(IMAGES_DIR, stale))
            print(f"  🗑 removed stale {os.path.join(IMAGES_DIR, stale)}")

    with open(IMAGES_AGGREGATE_HEADER_FILE, "w") as h:
        h.write("/**\n * @file images.h\n * @brief The full-screen 800x480 background bitmaps compiled into the firmware.\n")
        h.write(f" *\n * {GENERATED_NOTE}\n */\n")
        h.write("#ifndef IMAGES_H\n#define IMAGES_H\n\n#include \"config.h\"\n")
        for meme, group in grouped(images):
            h.write(f"\n#if {MEME_GUARD}\n" if meme else "\n")
            for name, _ in group:
                h.write(f'#include "images/image_{name}.h"\n')
            if meme:
                h.write(f"#endif  // {MEME_GUARD}\n")
        h.write("\n#endif  // IMAGES_H\n")
    return total


def format_generated(paths):
    """Run clang-format on the generated files, matching what the pre-commit hook would do."""
    tool = shutil.which("clang-format-20") or shutil.which("clang-format")
    if tool is None:
        print("⚠ clang-format not found; generated files left unformatted (the pre-commit hook will format them).")
        return
    subprocess.run([tool, "-i", *paths], check=True)


def process_font(font_name, sizes):
    """Process a font file in multiple sizes using fontconvert."""
    font_path = os.path.join("assets/fonts", font_name)
    if not os.path.exists(font_path):
        print(f"❌ Font file not found: {font_path}")
        return

    output_dir = os.path.join(OUTPUT_DIR, "fonts")
    os.makedirs(output_dir, exist_ok=True)

    for size in sizes:
        # Replace hyphens with underscores in the output filename
        base_name = os.path.splitext(font_name)[0].replace("-", "_")
        output_name = f"{base_name}{size}pt7b"
        output_path = os.path.join(output_dir, f"{output_name}.h")

        # Run fontconvert tool
        cmd = f"fontconvert {font_path} {size} > {output_path}"
        ret = os.system(cmd)
        if ret == 0:
            print(f"✔ Generated font header: {output_path}")
        else:
            print(f"❌ Failed to generate font: {output_path}")


def process_fonts():
    print("🔄 Processing fonts...")

    # Process only the fonts that are actually used in the project
    fonts_to_process = {
        "FunnelDisplay-Regular.ttf": [14],
        "FunnelDisplay-Bold.ttf": [18, 24, 32, 48, 60],
        "HelvetiPixel.ttf": [16, 24],
    }

    # Check the inputs exist *before* deleting anything, so a checkout without the (gitignored)
    # .ttf files or fontconvert can't wipe the committed src/fonts/.
    missing = [f for f in fonts_to_process if not os.path.exists(os.path.join("assets/fonts", f))]
    if missing or shutil.which("fontconvert") is None:
        raise SystemExit(f"❌ Can't regenerate fonts: missing {missing or 'fontconvert'}; src/fonts/ left untouched.")

    fonts_dir = os.path.join(OUTPUT_DIR, "fonts")
    if os.path.exists(fonts_dir):
        print(f"🗑 Removing existing fonts directory: {fonts_dir}")
        shutil.rmtree(fonts_dir)

    for font_name, sizes in fonts_to_process.items():
        process_font(font_name, sizes)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fonts", action="store_true", help="also regenerate src/fonts/")
    args = parser.parse_args()

    with open(MANIFEST_FILE) as f:
        manifest = json.load(f)

    print("🔄 Generating assets from", MANIFEST_FILE)
    icon_bytes = generate_icons(manifest["icons"])
    image_bytes = generate_images(manifest["images"])
    format_generated(
        [ICONS_HEADER_FILE, ICONS_SOURCE_FILE, IMAGES_AGGREGATE_HEADER_FILE]
        + [os.path.join(IMAGES_DIR, f"image_{name}.h") for name in manifest["images"]]
    )
    print(
        f"✔ Flash: {icon_bytes[False] + image_bytes[False]:,} B always, "
        f"+{icon_bytes[True] + image_bytes[True]:,} B with {MEME_GUARD}"
    )

    if args.fonts:
        process_fonts()
